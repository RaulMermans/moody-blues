"""A registered follow-up study: the causal design, pointed at a failure found during the sprint.

It reuses the causal suite's execution, eligibility and attribution unchanged. Only the world and
conditions differ, so nothing here can quietly be easier on one arm than the main study was.
"""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict

from moody_blues.contracts.agent import AgentConfigName
from moody_blues.evaluation.attribution import Attribution, assess_contrast
from moody_blues.evaluation.manifest import FROZEN_DIR, Condition, Faults, Manifest
from moody_blues.evaluation.suites import cell_of
from moody_blues.evaluation.trials import CellSummary, TrialRecord, summarize

FOLLOWUP_ID = "sprint-06-v2-followup"
FOLLOWUP_MANIFEST = FROZEN_DIR / "followup-manifest.json"
FOLLOWUP_PLAN = FROZEN_DIR / "followup-plan.json"
CAP_USD = 1.30

_PHANTOM: Faults = [{"kind": "phantom_success", "occurrence": 1}]
_STALE_FULL: Faults = [{"kind": "stale_read", "occurrence": 2, "span": 6}]
_STALE_REDUCED: Faults = [{"kind": "stale_read", "occurrence": 2, "span": 2}]


def build_followup(base: Manifest) -> Manifest:
    causal = base.causal.model_copy(
        update={
            "world": "w-e1",
            "conditions": (
                Condition(condition_id="clean", faults=[]),
                Condition(condition_id="phantom-only", faults=_PHANTOM),
                Condition(condition_id="stale-only", faults=_STALE_FULL),
                Condition(condition_id="reduced", faults=_PHANTOM + _STALE_REDUCED),
                Condition(condition_id="full", faults=_PHANTOM + _STALE_FULL),
            ),
            "fault_condition": "full",
            "reduced_condition": "reduced",
            "control_condition": "clean",
        }
    )
    return base.model_copy(
        update={
            "manifest_id": FOLLOWUP_ID,
            "causal": causal,
            "strategies": base.strategies.model_copy(
                update={"known_failure_key": "w-e1|baseline|phantom_success#1,stale_read#2x6"}
            ),
            "budget": base.budget.model_copy(
                update={
                    "causal_cap_usd": CAP_USD,
                    "strategies_cap_usd": 0.0,
                    "adaptation_cap_usd": 0.0,
                }
            ),
        }
    )


class FollowupResults(BaseModel):
    model_config = ConfigDict(frozen=True)

    manifest_id: str
    cells: list[CellSummary]
    contrasts: list[Attribution]


def followup_results(
    manifest: Manifest, trials: list[TrialRecord], *, extended: bool
) -> FollowupResults:
    suite = manifest.causal
    rule = suite.stage_two_rule if extended else suite.stage_one_rule

    def arm(condition: str, config: str = "baseline") -> list[TrialRecord]:
        return [t for t in trials if t.condition_id == condition and t.config == config]

    def against(control: str, changed: str) -> Attribution:
        return assess_contrast(
            fault_arm="full/baseline",
            fault=arm("full"),
            control_arm=f"{control}/baseline",
            control=arm(control),
            changed=changed,
            rule=rule,
        )

    hardened = AgentConfigName.HARDENED.value
    contrasts = [
        against("clean", "both faults removed"),
        against("phantom-only", "stale_read removed"),
        against("stale-only", "phantom_success removed"),
        against("reduced", "stale_read span 6 reduced to 2"),
        assess_contrast(
            fault_arm="full/baseline",
            fault=arm("full"),
            control_arm="full/hardened",
            control=arm("full", hardened),
            changed="only the recovery policy",
            rule=rule,
        ),
    ]
    cells = [
        summarize(cell, [t for t in trials if cell_of(t) == cell])
        for cell in (
            f"{c.condition_id}/{cfg.value}" for c in suite.conditions for cfg in suite.configs
        )
    ]
    return FollowupResults(manifest_id=manifest.manifest_id, cells=cells, contrasts=contrasts)


def render_followup(results: FollowupResults) -> str:
    out = [
        f"# Results: {results.manifest_id}",
        "",
        "_Generated by `moody-blues eval-report`. A follow-up study, not part of the registered "
        "conclusion. Unit: one fresh-world run._",
        "",
        "| Cell | Attempted | Eligible | Impaired (limits) | Provider/infra | Duplicates eligible "
        "| Duplicates impaired | Task success (eligible) | False completion | Honest not_completed "
        "| Mean tool calls | Tokens | Est. $ |",
        "|" + "---|" * 13,
    ]
    out += [
        f"| {c.label} | {c.attempted} | {c.eligible} | {c.impaired_by_limits} "
        f"| {c.provider_or_infrastructure} | {c.duplicates_eligible}/{c.eligible} "
        f"| {c.duplicates_impaired} | {c.task_success_eligible}/{c.eligible} "
        f"| {c.incorrect_completion_claims} | {c.honest_uncertainty} | {c.mean_tool_calls} "
        f"| {c.prompt_tokens + c.completion_tokens} | {c.estimated_cost_usd:.4f} |"
        for c in results.cells
    ]
    out += [
        "",
        "| Contrast | Changed | Fault arm | Control arm | Level | Reasons |",
        "|" + "---|" * 6,
    ]
    out += [
        f"| {a.fault_arm} vs {a.control_arm} | {a.changed} | {a.fault_failures}/{a.fault_eligible} "
        f"| {a.control_failures}/{a.control_eligible} | `{a.level.value}` "
        f"| {'; '.join(a.reasons) or 'rule met'} |"
        for a in results.contrasts
    ]
    return "\n".join(out) + "\n"

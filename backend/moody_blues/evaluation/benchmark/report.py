"""The generated tables. Numbers come from ``Results``; nothing here is written by hand."""

from __future__ import annotations

import csv
from pathlib import Path

from moody_blues.evaluation.benchmark.analysis import Results, StrategyRow, TrialRow, dumps


def _n(value: float | None, digits: int = 2) -> str:
    return "n/a" if value is None else f"{value:.{digits}f}"


_METRICS: tuple[tuple[str, str], ...] = (
    ("Investigations", "investigations"),
    ("Attempted experiments", "attempted"),
    ("Rejected before running", "rejected"),
    ("Executed", "executed"),
    ("Eligible", "eligible"),
    ("**Distinct verified per 10 eligible (primary)**", "per_10_eligible"),
    ("Distinct verified per 10 attempted", "per_10_attempted"),
    ("Distinct verified per 10 budgeted", "per_10_budget"),
    ("Distinct found per investigation", "distinct_found_per_investigation"),
    ("Investigations with a verified violation", "investigations_with_a_violation"),
    ("Runs with a verified violation", "verified_violation_runs"),
    ("Median position of first verified violation", "median_first_violation_position"),
    ("Median sandbox ms to first verified violation", "median_first_violation_ms"),
    ("Invalid proposal rate", "invalid_rate"),
    ("Undelivered-fault rate", "undelivered_rate"),
    ("Repeated-candidate rate", "repeated_candidate_rate"),
    ("Model calls", "model_calls"),
    ("Target tool calls", "tool_calls"),
    ("Prompt tokens", "prompt_tokens"),
    ("Completion tokens", "completion_tokens"),
    ("Model seconds", "model_seconds"),
    ("Sandbox seconds", "sandbox_seconds"),
    ("Wall seconds", "wall_seconds"),
    ("Model seconds per distinct found", "model_seconds_per_distinct"),
    ("Peak sampled Ollama memory, MB", "peak_ollama_rss_mb_sampled"),
    ("Investigations with complete evidence", "evidence_complete"),
)


def _table(rows: list[StrategyRow]) -> list[str]:
    head = "| Metric | " + " | ".join(r.strategy for r in rows) + " |"
    lines = [head, "|---|" + "---|" * len(rows)]
    for label, field in _METRICS:
        cells: list[str] = []
        for row in rows:
            value = getattr(row, field)
            cells.append(_n(value) if isinstance(value, float) or value is None else str(value))
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    return lines


def render(results: Results) -> str:
    lines = [
        "# Sprint 19 benchmark results",
        "",
        f"_Generated by `make bench-report` from raw evidence. Spec r{results.revision}, "
        f"sha256 `{results.spec_sha256}`. Do not edit._",
        "",
        f"**Comparative conclusion: `{results.conclusion}`**",
        "",
        *[f"- {r}" for r in results.conclusion_reasons],
        "",
        f"Main trials: {results.recorded_main} of {results.planned_main} recorded. "
        f"Adaptive eligible share: {results.gates.adaptive_eligible_share:.2f}. "
        f"Oracle and state disagreements: {results.oracle_state_disagreements}. "
        f"Sweep trials: {results.sweep_trials}.",
        "",
        "## All strategies",
        "",
        "Rates are a mean over units; seeds are averaged inside a unit first.",
        "",
        *_table(results.strategies),
        "",
    ]
    for world, rows in results.by_world.items():
        lines += [f"## {world}", "", *_table(rows), ""]
    lines += [
        "## Adaptive against each baseline, per unit",
        "",
        "| Baseline | Units | Adaptive | Baseline | Difference | Wins | Losses | Ties | "
        "95% exact CI, win share of non-ties |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for c in results.comparisons:
        interval = (
            "n/a"
            if c.win_share_interval is None
            else f"{c.win_share_interval[0]:.2f}-{c.win_share_interval[1]:.2f}"
        )
        lines.append(
            f"| {c.baseline} | {c.units} | {c.mean_adaptive:.2f} | {c.mean_baseline:.2f} | "
            f"{c.mean_difference:+.2f} | {c.wins} | {c.losses} | {c.ties} | {interval} |"
        )
    lines += [
        "",
        "## Every unit",
        "",
        "Rates are distinct verified per 10 eligible. Found is distinct per investigation. "
        "Reachable comes from the sweep, which no strategy saw. Expected is the exact mean over "
        "every possible random schedule.",
        "",
        "| Unit | Reachable | Fixed | Random | Adaptive | Found F | Found R | Found A | "
        "Expected R |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for u in results.units:
        codes = ", ".join(s.split(":", 1)[1] for s in u.reachable) or "none"
        lines.append(
            f"| {u.unit_id} | {codes} | {_n(u.fixed)} | {_n(u.random)} | {_n(u.adaptive)} | "
            f"{_n(u.found_fixed)} | {_n(u.found_random)} | {_n(u.found_adaptive)} | "
            f"{_n(u.expected_random_found)} |"
        )
    q = results.quality
    lines += [
        "",
        "## Investigator reasoning",
        "",
        f"{q.investigations} investigations, {q.hypotheses} hypotheses, {q.statements} checkable "
        f"statements, {q.incorrect_statements} incorrect "
        f"(rate {_n(q.incorrect_finding_rate)}). Exact repeats: {q.repeated_hypotheses} "
        f"(rate {_n(q.duplicate_hypothesis_rate)}).",
        "",
        "| Defect | Count |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in q.defects.items()],
        "",
        "| Rejected proposal reason | Count |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in q.rejected_by_reason.items()],
        "",
        "## Reproduction",
        "",
        "| Unit | Signature | Candidate | Reproduction | Without the fault |",
        "|---|---|---|---|---|",
        *[
            f"| {r.unit_id} | {r.signature} | {r.candidate} | {r.reproduction} | {r.contrast} |"
            for r in results.reproduction
        ],
        "",
    ]
    return "\n".join(lines)


def write(results: Results, rows: list[TrialRow], directory: Path) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "results.json").write_text(dumps(results), encoding="utf-8")
    (directory / "results.md").write_text(render(results), encoding="utf-8")
    with (directory / "experiments.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(
            [
                "trial_id",
                "unit_id",
                "strategy",
                "seed",
                "position",
                "experiment_id",
                "candidate",
                "validity",
                "eligible",
                "excluded_because",
                "verdict",
                "signatures",
                "repeated_candidate",
            ]
        )
        for row in rows:
            for e in row.experiments:
                writer.writerow(
                    [
                        row.trial_id,
                        row.unit_id,
                        row.strategy.value,
                        row.seed,
                        e.position,
                        e.experiment_id,
                        e.candidate,
                        e.validity,
                        e.eligible,
                        e.excluded_because,
                        e.verdict,
                        " ".join(e.signatures),
                        e.repeated_candidate,
                    ]
                )
